# sll 专项测试： sll rd, rt, sa  →  GPR[rd] = GPR[rt] << sa
    xori  $t0, $0, 1           # $8  = 1
    xori  $t1, $0, 0xffff      # $9  = 0x0000ffff
    lui   $t2, 0xf000          # $10 = 0xf0000000   高位已满，移位要丢位

    sll   $s0, $t0, 0          # sa=0   边界：一位都不移，$16 = 1
    sll   $s1, $t0, 1          # $17 = 2
    sll   $s2, $t0, 31         # sa=31  边界：$18 = 0x80000000
    sll   $s3, $t1, 16         # $19 = 0xffff0000
    sll   $s4, $t1, 17         # $20 = 0xfffe0000   最高位被移出去，不能回卷
    sll   $s5, $t2, 4          # $21 = 0            全部移出，只剩 0
    sll   $s6, $0,  5          # 源是 $0，$22 = 0

    sll   $0,  $t0, 3          # 写 $0：动作发生，GRF 不变
    # 注意：这里不能写助记符 nop。nop 和 sll $0,$0,0 机器码都是 0x00000000，
    # 但 MARS 从源码仿真，只给 sll 记写事件，给 nop 不记 —— 硬件分不出来，对不齐。
    sll   $0,  $0,  0          # 空转：写 $0，动作发生但 GRF 不变

    addu  $t3, $s2, $0         # 把 $18 读回来，证明 sa=31 真写进去了
